function renderZig(values) {
  const reserved = new Set(["var"]);
  const functions = values
    .map((tag) => {
      const rawName = tag.exportName === "varTag" ? "var" : tag.exportName;
      const name = reserved.has(rawName) ? `${rawName}_tag` : rawName;

      return `/// Creates a \`${tag.htmlName}\` element.
pub fn ${name}(
    properties_json: []const u8,
    children: []const ProgrammaticViewChild,
) ProgrammaticViewChild {
    return elements.tag("${tag.htmlName}", properties_json, children);
}`;
    })
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
const builtin = @import("builtin");

pub const ProgrammaticViewChild = u32;

pub const ProgrammaticViewTags = struct {
    namespace_uri: []const u8 = "",

    pub fn withNamespace(namespace_uri: []const u8) ProgrammaticViewTags {
        return .{ .namespace_uri = namespace_uri };
    }

    pub fn tag(
        self: ProgrammaticViewTags,
        name: []const u8,
        properties_json: []const u8,
        children: []const ProgrammaticViewChild,
    ) ProgrammaticViewChild {
        if (builtin.target.cpu.arch == .wasm32 or builtin.target.cpu.arch == .wasm64) {
            return view_tag(
                ptr(self.namespace_uri),
                len(self.namespace_uri),
                ptr(name),
                len(name),
                ptr(properties_json),
                len(properties_json),
                @intFromPtr(children.ptr),
                @intCast(children.len),
            );
        }
        return if (name.len == 0) 0 else 41;
    }
};

pub const elements = ProgrammaticViewTags{};

pub fn text(value: []const u8) ProgrammaticViewChild {
    if (builtin.target.cpu.arch == .wasm32 or builtin.target.cpu.arch == .wasm64) {
        return view_text(ptr(value), len(value));
    }
    return if (value.len == 0) 0 else 42;
}

pub fn release(child: ProgrammaticViewChild) bool {
    if (builtin.target.cpu.arch == .wasm32 or builtin.target.cpu.arch == .wasm64) {
        return view_release(child) != 0;
    }
    return child != 0;
}

extern "angular_ts" fn view_tag(
    namespace_ptr: u32,
    namespace_len: u32,
    name_ptr: u32,
    name_len: u32,
    properties_ptr: u32,
    properties_len: u32,
    children_ptr: u32,
    children_len: u32,
) ProgrammaticViewChild;
extern "angular_ts" fn view_text(value_ptr: u32, value_len: u32) ProgrammaticViewChild;
extern "angular_ts" fn view_release(child: ProgrammaticViewChild) u32;

fn ptr(value: []const u8) u32 {
    return @intCast(@intFromPtr(value.ptr));
}

fn len(value: []const u8) u32 {
    return @intCast(value.len);
}

${functions}
`;
}
