import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(
  path.join(root, "src/core/compile/programmatic-view.ts"),
  "utf8",
);
const check = process.argv.includes("--check");
const requested = readOption("--integration");
const names = Array.from(
  source.matchAll(
    /^export const ([A-Za-z][A-Za-z0-9]*): ProgrammaticViewTag/gm,
  ),
  (match) => match[1],
);

if (names.length < 100) {
  throw new Error(
    `Expected at least 100 HTML tag factories; found ${names.length}.`,
  );
}

const tags = names.map((exportName) => ({
  exportName,
  htmlName: exportName === "varTag" ? "var" : exportName,
}));
const outputs = {
  dart: [
    "integrations/dart/lib/src/programmatic_view_tags.dart",
    renderDart(tags),
  ],
  gleam: [
    "integrations/gleam/src/angular_ts/view_tags.gleam",
    renderGleam(tags),
  ],
  kotlin: [
    "integrations/kotlin/src/jsMain/kotlin/angular/ts/ProgrammaticViewTags.kt",
    renderKotlin(tags),
  ],
  scala: [
    "integrations/scala/src/main/scala/angular/ts/ProgrammaticViewTags.scala",
    renderScala(tags),
  ],
  clojurescript: [
    "integrations/closure/clojurescript/src/angular_ts/view.cljs",
    renderClojureScript(tags),
  ],
  javaTags: [
    "integrations/closure/java/src/main/java/org/angular/ts/view/Tags.java",
    renderJavaTags(tags),
  ],
};

for (const [integration, [relativePath, content]] of Object.entries(outputs)) {
  if (requested && requested !== integration) continue;

  const filename = path.join(root, relativePath);
  const current = fs.existsSync(filename)
    ? fs.readFileSync(filename, "utf8")
    : undefined;

  if (check) {
    if (current !== content) {
      console.error(`${relativePath} is out of date. Run:`);
      console.error(
        `  node utils/generate-programmatic-view-tags.mjs --integration ${integration}`,
      );
      process.exitCode = 1;
    }
  } else {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, content);
  }
}

function readOption(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
}

function publicName(tag, reserved) {
  return reserved.has(tag.exportName) ? `${tag.exportName}Tag` : tag.exportName;
}

function renderDart(values) {
  const functions = values
    .map(
      (tag) => `/// Creates a \`${tag.htmlName}\` element.
Element ${tag.exportName}({
  Map<String, Object?> properties = const {},
  List<Object?> children = const [],
}) =>
    AngularTsRuntime.global().tags.tag(
          '${tag.htmlName}',
          properties: properties,
          children: children,
        );`,
    )
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
import 'package:web/web.dart';

import 'runtime.dart';

${functions}
`;
}

function renderGleam(values) {
  const reserved = new Set(["case", "fn", "if", "let", "type", "use"]);
  const functions = values
    .map((tag) => {
      const name = publicName(tag, reserved).replace(
        /[A-Z]/g,
        (value) => `_${value.toLowerCase()}`,
      );
      return `/// Creates a \`${tag.htmlName}\` element.
pub fn ${name}(
  properties: List(programmatic_view.Property),
  children: List(Dynamic),
) -> Dynamic {
  programmatic_view.tag("${tag.htmlName}", properties, children)
}`;
    })
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
import angular_ts/programmatic_view
import gleam/dynamic.{type Dynamic}

${functions}
`;
}

function renderKotlin(values) {
  const reserved = new Set([
    "as",
    "break",
    "class",
    "continue",
    "do",
    "else",
    "false",
    "for",
    "fun",
    "if",
    "in",
    "interface",
    "is",
    "null",
    "object",
    "package",
    "return",
    "super",
    "this",
    "throw",
    "true",
    "try",
    "typealias",
    "typeof",
    "val",
    "var",
    "when",
    "while",
  ]);
  const functions = values
    .map((tag) => {
      const name = publicName(tag, reserved);
      return `/** Creates a \`${tag.htmlName}\` element. */
public fun ${name}(
    properties: Map<String, Any?> = emptyMap(),
    vararg children: Any?,
): Element = ProgrammaticTags(angularRuntime.view.tags).tag(
    "${tag.htmlName}",
    properties,
    *children,
)`;
    })
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
package angular.ts

import org.w3c.dom.Element

${functions}
`;
}

function renderScala(values) {
  const reserved = new Set([
    "class",
    "def",
    "enum",
    "export",
    "extends",
    "given",
    "if",
    "import",
    "match",
    "new",
    "object",
    "then",
    "trait",
    "type",
    "val",
    "var",
    "while",
    "with",
  ]);
  const functions = values
    .map((tag) => {
      const name = publicName(tag, reserved);
      return `  /** Creates a \`${tag.htmlName}\` element. */
  def ${name}(
      properties: Map[String, js.Any] = Map.empty,
      children: js.Any*,
  ): dom.Element = AngularTS.tags.tag("${tag.htmlName}", properties, children*)`;
    })
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
package angular.ts

import org.scalajs.dom
import scala.scalajs.js

object tags:
${functions}
`;
}

function renderClojureScript(values) {
  const reserved = new Set(["map", "meta", "time"]);
  const functions = values
    .map((tag) => {
      const name = reserved.has(tag.exportName)
        ? `${tag.exportName}-tag`
        : tag.exportName;

      return `(defn ${name}
  "Creates a ${tag.htmlName} element."
  [& args]
  (apply tag "${tag.htmlName}" args))`;
    })
    .join("\n\n");

  return `;; Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
(ns angular-ts.view)

(defn- call-view [name & args]
  (.apply (aget (.-view js/angular) name) nil (to-array args)))

(defn tag
  "Creates an HTML element by name."
  [name & args]
  (.apply (aget (.-tags js/angular) name) nil (to-array args)))

(defn tag-ns
  "Creates a namespaced element by name."
  [namespace-uri name & args]
  (.apply (aget ((.-tags js/angular) namespace-uri) name) nil (to-array args)))

(defn event
  ([listener] (call-view "event" listener))
  ([listener options] (call-view "event" listener options)))

(defn attrs [values]
  (call-view "attrs" (clj->js values)))

(defn props [values]
  (call-view "props" (clj->js values)))

(defn each [read key render]
  (call-view "each" read key render))

${functions}
`;
}

function renderJavaTags(values) {
  const reserved = new Set(["assert", "enum", "interface", "native"]);
  const methods = values
    .map((tag) => {
      const name = publicName(tag, reserved);
      return `  /** Creates a {@code ${tag.htmlName}} element. */
  @JsMethod(namespace = "angular.tags", name = "${tag.htmlName}")
  public static native HTMLElement ${name}(Object... arguments);`;
    })
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
package org.angular.ts.view;

import elemental2.dom.HTMLElement;
import jsinterop.annotations.JsMethod;

/** Direct, typed entry points for AngularTS HTML tag factories. */
public final class Tags {
  private Tags() {}

${methods}
}
`;
}
