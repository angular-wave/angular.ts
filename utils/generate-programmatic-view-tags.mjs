function renderAssemblyScript(values) {
  const functions = values
    .map(
      (tag) => `/** Creates a \`${tag.htmlName}\` element. */
export function ${tag.exportName}(
  propertiesJson: string = "{}",
  children: Array<ProgrammaticViewChild> = [],
): ProgrammaticViewChild {
  return tags.tag("${tag.htmlName}", propertiesJson, children);
}`,
    )
    .join("\n\n");

  return `// Generated by utils/generate-programmatic-view-tags.mjs. Do not edit.
@external("angular_ts", "view_tag")
declare function hostViewTag(
  namespacePtr: usize,
  namespaceLen: i32,
  namePtr: usize,
  nameLen: i32,
  propertiesPtr: usize,
  propertiesLen: i32,
  childrenPtr: usize,
  childrenLen: i32,
): u32;

@external("angular_ts", "view_text")
declare function hostViewText(valuePtr: usize, valueLen: i32): u32;

@external("angular_ts", "view_release")
declare function hostViewRelease(handle: u32): u32;

export type ProgrammaticViewChild = u32;
export type ProgrammaticViewProperties = string;

export class ProgrammaticViewTags {
  constructor(public namespaceUri: string = "") {}

  withNamespace(namespaceUri: string): ProgrammaticViewTags {
    return new ProgrammaticViewTags(namespaceUri);
  }

  tag(
    name: string,
    propertiesJson: ProgrammaticViewProperties = "{}",
    children: Array<ProgrammaticViewChild> = [],
  ): ProgrammaticViewChild {
    const namespaceBuffer = String.UTF8.encode(this.namespaceUri);
    const nameBuffer = String.UTF8.encode(name);
    const propertiesBuffer = String.UTF8.encode(propertiesJson);

    return hostViewTag(
      changetype<usize>(namespaceBuffer),
      namespaceBuffer.byteLength,
      changetype<usize>(nameBuffer),
      nameBuffer.byteLength,
      changetype<usize>(propertiesBuffer),
      propertiesBuffer.byteLength,
      children.dataStart,
      children.length,
    );
  }
}

export const tags = new ProgrammaticViewTags();

export function text(value: string): ProgrammaticViewChild {
  const buffer = String.UTF8.encode(value);
  return hostViewText(changetype<usize>(buffer), buffer.byteLength);
}

export function releaseView(child: ProgrammaticViewChild): bool {
  return hostViewRelease(child) != 0;
}

${functions}
`;
}

