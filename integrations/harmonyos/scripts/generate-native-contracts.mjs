#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateNativeCapabilityCatalog } from "../../native/scripts/native-capabilities-schema.mjs";
import { validateNativeElementCatalog } from "../../native/scripts/native-elements-schema.mjs";

const integrationRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const nativeRoot = resolve(integrationRoot, "../native");
const outputRoot = resolve(integrationRoot, "packages/core/src/main/ets/generated");
const check = process.argv.includes("--check");
const [elements, capabilities] = await Promise.all([
  readJson(resolve(nativeRoot, "native-elements.json")),
  readJson(resolve(nativeRoot, "native-capabilities.json")),
]);

validateNativeElementCatalog(elements);
validateNativeCapabilityCatalog(capabilities);

const outputs = [
  {
    path: resolve(outputRoot, "NativeElementCatalog.ts"),
    value: renderCatalog("nativeElements", elements.elements),
  },
  {
    path: resolve(outputRoot, "NativeCapabilityCatalog.ts"),
    value: renderCatalog("nativeCapabilities", capabilities.capabilities),
  },
];

let stale = false;
for (const output of outputs) {
  if (check) {
    const current = await readFile(output.path, "utf8").catch(() => "");
    if (current !== output.value) {
      console.error(`${output.path} is out of date.`);
      stale = true;
    }
  } else {
    await mkdir(dirname(output.path), { recursive: true });
    await writeFile(output.path, output.value);
  }
}

if (stale) {
  console.error("Run make -C integrations/harmonyos generate-native-contracts.");
  process.exitCode = 1;
}

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

function renderCatalog(name, entries) {
  const keyed = Object.fromEntries(entries.map((entry) => [entry.name, entry]));
  return `// Generated by integrations/harmonyos/scripts/generate-native-contracts.mjs.\n// Do not edit directly.\n\nexport const ${name} = ${JSON.stringify(keyed, null, 2)} as const;\n`;
}
